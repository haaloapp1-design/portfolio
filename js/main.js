/* Portfolio behaviour: project rendering, filters, mobile menu.
   Project data comes from data/projects.js, which is generated by
   scripts/build-projects.mjs from the folders inside /projects. */
(function () {
  "use strict";

  var projects = (window.PROJECTS || []).slice();
  var featuredEl = document.getElementById("featured");
  var rowsEl = document.getElementById("project-rows");
  var filtersEl = document.getElementById("filters");
  var emptyEl = document.getElementById("projects-empty");
  var active = "All";

  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }

  // Pick dark or light text for a cover colour.
  function textOn(hex) {
    var h = (hex || "#27348b").replace("#", "");
    if (h.length === 3) h = h.replace(/(.)/g, "$1$1");
    var r = parseInt(h.substr(0, 2), 16), g = parseInt(h.substr(2, 2), 16), b = parseInt(h.substr(4, 2), 16);
    return (0.299 * r + 0.587 * g + 0.114 * b) > 160 ? "#141a3a" : "#ffffff";
  }

  function statusClass(s) {
    s = (s || "").toLowerCase();
    if (/live|published|in use|shipped/.test(s)) return "live";
    if (/development|progress|pilot|building/.test(s)) return "wip";
    return "";
  }

  function metaHtml(p) {
    var out = "";
    if (p.status) out += '<span class="status ' + statusClass(p.status) + '">' + esc(p.status) + "</span>";
    (p.tech || []).forEach(function (t) { out += '<span class="tag">' + esc(t) + "</span>"; });
    return '<div class="meta">' + out + "</div>";
  }

  function linksHtml(p) {
    var l = p.links || {}, out = "";
    if (l.live) out += '<a href="' + esc(l.live) + '" target="_blank" rel="noopener">Open the live project</a>';
    if (l.repo) out += '<a href="' + esc(l.repo) + '" target="_blank" rel="noopener">View the code</a>';
    if (l.store) out += '<a href="' + esc(l.store) + '" target="_blank" rel="noopener">See it in the store</a>';
    return out ? '<div class="links">' + out + "</div>" : "";
  }

  function coverHtml(p) {
    var c = p.color || "#27348b";
    var style = ' style="--c:' + esc(c) + ";--t:" + textOn(c) + '"';
    if (p.cover) {
      return '<div class="cover has-img"' + style + '><img src="projects/' + esc(p.slug) + "/" + esc(p.cover) +
        '" alt="' + esc(p.title) + ' screenshot" loading="lazy"></div>';
    }
    return '<div class="cover"' + style + '><span class="cover-word">' + esc(p.short || p.title) + "</span></div>";
  }

  function render() {
    var list = projects.filter(function (p) { return active === "All" || p.category === active; });
    var feat = list.filter(function (p) { return p.featured; });
    var rest = list.filter(function (p) { return !p.featured; });

    featuredEl.innerHTML = feat.map(function (p) {
      return '<article class="feature">' + coverHtml(p) +
        '<div class="feature-body"><h3>' + esc(p.title) + "</h3>" +
        '<p class="tagline">' + esc(p.tagline) + "</p>" +
        '<p class="desc">' + esc(p.description) + "</p>" +
        metaHtml(p) + linksHtml(p) + "</div></article>";
    }).join("");

    rowsEl.innerHTML = rest.map(function (p) {
      return '<article class="row"><span class="year">' + esc(p.year) + "</span>" +
        '<div><h3><span class="swatch" style="--c:' + esc(p.color || "#27348b") + '"></span>' + esc(p.title) + "</h3>" +
        '<p class="tagline">' + esc(p.tagline) + "</p></div>" +
        '<div class="desc-col"><p>' + esc(p.description) + "</p>" + metaHtml(p) + linksHtml(p) + "</div></article>";
    }).join("");

    featuredEl.hidden = feat.length === 0;
    rowsEl.hidden = rest.length === 0;
    emptyEl.hidden = list.length !== 0;
  }

  function buildFilters() {
    var cats = ["All"];
    projects.forEach(function (p) { if (p.category && cats.indexOf(p.category) < 0) cats.push(p.category); });
    filtersEl.innerHTML = cats.map(function (c) {
      return '<button class="chip" type="button" aria-pressed="' + (c === active) + '" data-cat="' + esc(c) + '">' + esc(c) + "</button>";
    }).join("");
    filtersEl.addEventListener("click", function (e) {
      var b = e.target.closest(".chip");
      if (!b) return;
      active = b.getAttribute("data-cat");
      Array.prototype.forEach.call(filtersEl.children, function (x) {
        x.setAttribute("aria-pressed", String(x === b));
      });
      render();
    });
  }

  if (featuredEl) { buildFilters(); render(); }

  // Portrait: try profile.png, then profile.jpg, then the placeholder.
  var portrait = document.getElementById("portrait");
  if (portrait) {
    var tries = ["assets/profile.jpg", "assets/profile-placeholder.svg"];
    portrait.addEventListener("error", function () {
      if (tries.length) portrait.src = tries.shift();
    });
    if (portrait.complete && portrait.naturalWidth === 0) portrait.src = tries.shift();
  }

  // Mobile menu
  var toggle = document.querySelector(".nav-toggle");
  var links = document.getElementById("nav-links");
  if (toggle && links) {
    toggle.addEventListener("click", function () {
      var open = links.classList.toggle("open");
      toggle.setAttribute("aria-expanded", String(open));
      toggle.setAttribute("aria-label", open ? "Close menu" : "Open menu");
    });
    links.addEventListener("click", function (e) {
      if (e.target.tagName === "A") {
        links.classList.remove("open");
        toggle.setAttribute("aria-expanded", "false");
      }
    });
  }

  var nav = document.querySelector(".nav");
  function onScroll() { nav.classList.toggle("scrolled", window.scrollY > 8); }
  window.addEventListener("scroll", onScroll, { passive: true });
  onScroll();

  var y = document.getElementById("year");
  if (y) y.textContent = new Date().getFullYear();
})();
